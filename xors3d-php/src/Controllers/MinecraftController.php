    private function buildTemplates(Engine $e): void
    {
        $base = dirname(__DIR__, 2) . '/assets/blocks/';
        foreach (self::TYPES as $id => [$name, $file]) {
            $cube = $e->xCreateCube();
            if ($id === 1) {
                $w = $e->xMeshWidth($cube);
                $this->scale = $w > 0.0 ? self::BLOCK / $w : 1.0;
            }
            $e->xScaleEntity($cube, $this->scale, $this->scale, $this->scale);
            // glass loads as a MASKED texture: fully-transparent texels are discarded so
            // you see straight through the pane, the frame stays solid (crisp windows).
            $texture = ($id === 10 || $id === self::DOOR)
                ? $e->xLoadTexture($base . $file, 1 + 4 + 8)   // color + masked + mipmap (glass/door)
                : $e->xLoadTexture($base . $file);
            $this->tex[$id] = $texture;
            $e->xEntityTexture($cube, $texture);
            if ($id === 11) { $e->xEntityFX($cube, 1); } // glowstone: fullbright
            $e->xHideEntity($cube);
            $this->template[$id] = $cube;

            // brush per type for the merged chunk-mesh surfaces
            $b = $e->xCreateBrush();
            $e->xBrushTexture($b, $texture);
            $this->brush[$id] = $b;
        }

        // animated translucent water
        $this->waterTex = $e->xLoadAnimTexture($base . 'water.png', 1, 16, 16, 0, 32);
        $this->waterTpl = $e->xCreateCube();
        $e->xScaleEntity($this->waterTpl, $this->scale, $this->scale, $this->scale);
        $e->xEntityColor($this->waterTpl, 120, 160, 255);
        $e->xEntityAlpha($this->waterTpl, 0.7);
        $e->xEntityTexture($this->waterTpl, $this->waterTex);
        $e->xHideEntity($this->waterTpl);
    }

    private function createHand(Engine $e, int $camera): void
    {
        $this->hand = $e->xCreateCube();
        $s = $this->scale * 0.22;
        $e->xScaleEntity($this->hand, $s, $s, $s);
        $e->xEntityParent($this->hand, $camera);
        $e->xEntityFX($this->hand, 1);
        $e->xPositionEntity($this->hand, 0.95, -0.75, 2.6, 0);
        $e->xRotateEntity($this->hand, 15, 35, 0, 0);
        $this->refreshHand($e);
    }

    private function refreshHand(Engine $e): void
    {
        if ($this->hand !== 0) {
            $e->xEntityTexture($this->hand, $this->tex[$this->selectedType()]);
        }
    }

    // ============================================================ world (gen)

    /** Free all instantiated entities; keep the data model (height/edits). */
    private function clearWorld(): void
    {
        $e = $this->e;
        $this->clearMobs();
        foreach ($this->chunk as $list) {
            foreach ($list as $h) { $e->xFreeEntity($h); }
        }
        $this->chunk = $this->chunkMesh = $this->meshCk = $this->water = $this->loaded = [];
        $this->streamCX = PHP_INT_MAX;
        $this->streamCZ = PHP_INT_MAX;
    }

    private function rebuildWorld(): void
    {
        $this->clearWorld();
        $this->edits = [];
        $this->editsByChunk = [];
        $this->lightCells = [];
        $this->treeGen = [];
        $this->height = [];
        $this->biome = [];
        $this->generateData();
    }

    /**
     * Infinite world: nothing is precomputed. The height map, ores and trees are
     * generated procedurally per column/chunk on demand as the player explores
     * (see heightAt / groundType / loadChunk). Only a new random seed + mobs.
     */
    private function generateData(): void
    {
        $this->seed = mt_rand() / mt_getrandmax() * 1000.0;
        $this->starterKit();
        $this->buildStructures();
    }


    /** Spawn a small burst of textured cube shards when a block is broken. */
    private function spawnBreakParticles(int $x, int $y, int $z, int $type): void
    {
        $e = $this->e; $B = self::BLOCK;
        $tex = $this->tex[$type] ?? 0;
        if ($tex === 0) { return; }
        $cx = $x * $B; $cy = $y * $B; $cz = $z * $B;
        for ($i = 0; $i < 7; $i++) {
            $c = $e->xCreateCube();
            $s = $this->scale * (0.12 + mt_rand(0, 8) / 100.0);
            $e->xScaleEntity($c, $s, $s, $s);
            $e->xEntityTexture($c, $tex);
            $ox = (mt_rand(-40, 40) / 100.0) * $B; $oy = (mt_rand(-30, 40) / 100.0) * $B; $oz = (mt_rand(-40, 40) / 100.0) * $B;
            $e->xPositionEntity($c, $cx + $ox, $cy + $oy, $cz + $oz);
            $this->particles[] = [
                'ent' => $c, 'x' => $cx + $ox, 'y' => $cy + $oy, 'z' => $cz + $oz,
                'vx' => (mt_rand(-15, 15) / 100.0) * $B, 'vy' => (mt_rand(15, 38) / 100.0) * $B,
                'vz' => (mt_rand(-15, 15) / 100.0) * $B, 'life' => mt_rand(18, 30),
            ];
        }
        // cap the pool: drop the oldest bursts if it grows too large
        while (count($this->particles) > 140) {
            $p = array_shift($this->particles);
            $e->xFreeEntity($p['ent']);
        }
    }

    /** Advance and expire block-break particles (gravity + fade to removal). */
    private function updateParticles(): void
    {
        if ($this->particles === []) { return; }
        $e = $this->e; $dt = $this->dt;
        foreach ($this->particles as $i => &$p) {
            $p['vy'] -= self::G * 0.6 * $dt;
            $p['x'] += $p['vx'] * $dt; $p['y'] += $p['vy'] * $dt; $p['z'] += $p['vz'] * $dt;
            $p['life'] -= $dt;
            if ($p['life'] <= 0) { $e->xFreeEntity($p['ent']); unset($this->particles[$i]); continue; }
            $e->xPositionEntity($p['ent'], $p['x'], $p['y'], $p['z']);
        }
        unset($p);
    }

    /** Reassign the point-light pool to the nearest torches/glowstone around the player. */
    private function updatePointLights(): void
    {
        if ($this->pointLights === []) { return; }
        $e = $this->e; $B = self::BLOCK;
        $reach = 26.0 * $B; $reach2 = $reach * $reach;
        $px = $this->px; $py = $this->py; $pz = $this->pz;
        $near = [];
        foreach ($this->lightCells as [$x, $y, $z]) {
            $wx = $x * $B; $wy = $y * $B; $wz = $z * $B;
            $dx = $wx - $px; $dy = $wy - $py; $dz = $wz - $pz;
            $d2 = $dx * $dx + $dy * $dy + $dz * $dz;
            if ($d2 < $reach2) { $near[] = [$d2, $wx, $wy, $wz]; }
        }
        sort($near); // nearest first (by squared distance)
        foreach ($this->pointLights as $i => $l) {
            if (isset($near[$i])) {
                [, $wx, $wy, $wz] = $near[$i];
                $e->xPositionEntity($l, $wx, $wy + $B * 0.3, $wz);
                $e->xShowEntity($l);
            } else {
                $e->xHideEntity($l);
            }
        }
    }

    private function clearMobs(): void
    {
        foreach ($this->mobs as $m) {
            foreach ($m['parts'] as $p) { $this->e->xFreeEntity($p); }
            $this->e->xFreeEntity($m['pivot']);
        }
        $this->mobs = [];
    }

