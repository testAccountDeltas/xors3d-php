    private function adjust(array $opt, int $dir): void
    {
        $k = $opt['key'];
        switch ($opt['type']) {
            case 'bool':
                $this->settings[$k] = (int) !((int) $this->settings[$k]);
                break;
            case 'int':
                $this->settings[$k] = (int) max($opt['min'], min($opt['max'], (int) $this->settings[$k] + $dir * $opt['step']));
                break;
            case 'float':
                $v = (float) $this->settings[$k] + $dir * $opt['step'];
                $this->settings[$k] = round(max($opt['min'], min($opt['max'], $v)), 2);
                break;
            case 'res':
                $cur = 0;
                foreach (self::RESOLUTIONS as $i => [$rw, $rh]) {
                    if ((int) $this->settings['width'] === $rw && (int) $this->settings['height'] === $rh) { $cur = $i; }
                }
                $cur = ($cur + $dir + count(self::RESOLUTIONS)) % count(self::RESOLUTIONS);
                [$this->settings['width'], $this->settings['height']] = self::RESOLUTIONS[$cur];
                break;
        }
        $this->applySettings();
        $this->saveSettings();
    }

    private function orbitBackdrop(): void
    {
        $e = $this->e;
        $mid = ($this->wsize / 2) * self::BLOCK;
        $t = $e->xMillisecs() / 4000.0;
        $r = $this->wsize * self::BLOCK * 0.85;
        $e->xPositionEntity($this->pivot, $mid, self::MAX_H * self::BLOCK, $mid);
        $e->xPositionEntity($this->camH, $mid + cos($t) * $r, (self::MAX_H + 6) * self::BLOCK, $mid + sin($t) * $r);
        $e->xPointEntity($this->camH, $this->pivot);
        $this->updateSky();
        $this->updateSkyObjects();
        $this->animateWater();
        $this->updateMobs();
        $e->xRenderWorld();
    }

    // ================================================================ gameplay

    /** True if a solid (non-water) block occupies this voxel cell. */
    private function solidCell(int $bx, int $by, int $bz): bool
    {
        return isset($this->cell[$this->key($bx, $by, $bz)]);
    }

    private function cellOf(float $w): int
    {
        return (int) floor(($w + self::BLOCK / 2) / self::BLOCK);
    }

    private function move(): void
    {
        $e = $this->e;
        $fly = $this->fly;

        // direction from camera transform (so it follows where you look)
        $e->xTFormVector(0, 0, 1, $this->camH, 0);
        $fwx = $e->xTFormedX(); $fwy = $e->xTFormedY(); $fwz = $e->xTFormedZ();
        $e->xTFormVector(1, 0, 0, $this->camH, 0);
        $rgx = $e->xTFormedX(); $rgy = $e->xTFormedY(); $rgz = $e->xTFormedZ();

        if (!$fly) { // project onto XZ for walking
            $fl = hypot($fwx, $fwz) ?: 1.0; $fwx /= $fl; $fwz /= $fl; $fwy = 0.0;
            $rl = hypot($rgx, $rgz) ?: 1.0; $rgx /= $rl; $rgz /= $rl; $rgy = 0.0;
        }

        $spd = $fly ? self::SPD_FLY : self::SPD_WALK;
        $mx = $my = $mz = 0.0;
        if ($e->xKeyDown(Constants::KEY_W)) { $mx += $fwx; $my += $fwy; $mz += $fwz; }
        if ($e->xKeyDown(Constants::KEY_S)) { $mx -= $fwx; $my -= $fwy; $mz -= $fwz; }
        if ($e->xKeyDown(Constants::KEY_D)) { $mx += $rgx; $my += $rgy; $mz += $rgz; }
        if ($e->xKeyDown(Constants::KEY_A)) { $mx -= $rgx; $my -= $rgy; $mz -= $rgz; }
        $ml = hypot(hypot($mx, $my), $mz);
        if ($ml > 0.0) { $mx = $mx / $ml * $spd; $my = $my / $ml * $spd; $mz = $mz / $ml * $spd; }

        $moving = $ml > 0.0;

        if ($fly) {
            $this->px += $mx; $this->py += $my; $this->pz += $mz;
            if ($e->xKeyDown(Constants::KEY_SPACE))  { $this->py += $spd; }
            if ($e->xKeyDown(Constants::KEY_LSHIFT)) { $this->py -= $spd; }
        } else {
            $this->moveAxisX($mx);
            $this->moveAxisZ($mz);
            $this->applyGravity();
            if ($this->onGround && $e->xKeyHit(Constants::KEY_SPACE)) { $this->vy = self::JUMP; }
            // footsteps
            if ($moving && $this->onGround) {
                $now = $e->xMillisecs();
                if ($now - $this->lastStep > 340) { $this->play($this->sndStep); $this->lastStep = $now; }
            }
            if ($this->py < -30.0) { $this->spawnPlayer(); } // fell out of the world
        }

        $e->xPositionEntity($this->camH, $this->px, $this->py + self::EYE, $this->pz);
    }

    private function blockedAt(float $x, float $z): bool
    {
        $bx = $this->cellOf($x); $bz = $this->cellOf($z);
        $c1 = $this->cellOf($this->py + 0.2);
        $c2 = $this->cellOf($this->py + self::PH - 0.2);
        return $this->solidCell($bx, $c1, $bz) || $this->solidCell($bx, $c2, $bz);
    }

    private function moveAxisX(float $mx): void
    {
        if ($mx === 0.0) { return; }
        $tx = $this->px + $mx + ($mx > 0 ? self::HW : -self::HW);
        if (!$this->blockedAt($tx, $this->pz)) { $this->px += $mx; }
    }

    private function moveAxisZ(float $mz): void
    {
        if ($mz === 0.0) { return; }
        $tz = $this->pz + $mz + ($mz > 0 ? self::HW : -self::HW);
        if (!$this->blockedAt($this->px, $tz)) { $this->pz += $mz; }
    }

    private function applyGravity(): void
    {
        $this->vy -= self::G;
        $ny = $this->py + $this->vy;
        $bx = $this->cellOf($this->px); $bz = $this->cellOf($this->pz);

        if ($this->vy <= 0.0) {
            $fc = $this->cellOf($ny);
            if ($this->solidCell($bx, $fc, $bz)) {
                $this->py = $fc * self::BLOCK + self::BLOCK / 2 + 0.02;
                $this->vy = 0.0;
                $this->onGround = true;
                return;
            }
            $this->onGround = false;
        } else {
            $hc = $this->cellOf($this->py + self::PH + $this->vy);
            if ($this->solidCell($bx, $hc, $bz)) { $this->vy = 0.0; return; }
        }
        $this->py = $ny;
    }

    private function animateWater(): void
    {
        if ($this->waterTex === 0 || $this->waterList === []) { return; }
        $frame = (int) ($this->e->xMillisecs() / 90) % 32;
        foreach ($this->waterList as $w) {
            $this->e->xEntityTexture($w, $this->waterTex, $frame);
        }
    }

    private function gameLoop(int $max): void
    {
        $e = $this->e; $h = $this->camH; $frame = 0;

        while (true) {
            if ($this->closeRequested()) { $this->quit = true; return; }
            if ($max === 0 && $e->xKeyHit(Constants::KEY_ESCAPE)) { return; }

            if ($e->xKeyHit(Constants::KEY_F)) { $this->fly = !$this->fly; $this->vy = 0.0; }

            $this->cam->lookOnly();
            $this->move();
            $this->updateChunks();
            $this->animateWater();
            $this->updateMobs();

            // block selection: number keys 1-9 + mouse wheel
            for ($n = 1; $n <= count(self::HOTBAR); $n++) {
                if ($e->xKeyHit(Constants::KEY_1 + ($n - 1))) { $this->slot = $n - 1; $this->refreshHand($e); }
            }
            $wheel = $e->xMouseZSpeed();
            if ($wheel !== 0) {
                $c = count(self::HOTBAR);
                $this->slot = (($this->slot - ($wheel > 0 ? 1 : -1)) % $c + $c) % $c;
                $this->refreshHand($e);
            }
            $e->xTurnEntity($this->hand, 0, 1.5, 0);
            $this->updateSky();
            $this->updateSkyObjects();

            $cx = (int) ($e->xGraphicsWidth() / 2);
            $cy = (int) ($e->xGraphicsHeight() / 2);
            $e->xCameraPick($h, $cx, $cy);
            $picked = $e->xPickedEntity();
            $hasTarget = $picked !== 0 && isset($this->entToCell[$picked]);

            if ($hasTarget) {
                [$bx, $by, $bz] = array_map('intval', explode(',', $this->entToCell[$picked]));
                if ($e->xMouseHit(1)) {
                    $this->destroyAt($e, $bx, $by, $bz);
                } elseif ($e->xMouseHit(2) || $e->xMouseHit(3)) {
                    [$dx, $dy, $dz] = $this->faceOffset($e);
                    $this->placeAt($e, $bx + $dx, $by + $dy, $bz + $dz, $this->selectedType());
                }
            }

            $e->xRenderWorld();
            $this->renderBloom();
            $this->drawHud($e, $hasTarget);

            if ($max > 0 && $frame + 1 >= $max && ($shot = getenv('CRAFT_SHOT'))) {
                $e->xSaveBuffer($e->xBackBuffer(), $shot);
            }
            $e->xFlip();
            if ($max > 0 && ++$frame >= $max) { return; }
        }
    }

    private function drawHud(Engine $e, bool $hasTarget): void
    {
        $w = $e->xGraphicsWidth();
        $cx = (int) ($w / 2);
        $cy = (int) ($e->xGraphicsHeight() / 2);

        // crosshair (two lines)
        $e->xColor(255, 255, 255);
        $e->xLine($cx - 9, $cy, $cx + 9, $cy);
        $e->xLine($cx, $cy - 9, $cx, $cy + 9);

        $e->xColor(255, 255, 0);
        $e->xText(10, 10, 'FPS: ' . $e->xGetFPS());
        $e->xColor(220, 220, 220);
        $e->xText(10, 30, 'Blocks: ' . count($this->cell) . '   Sheep: ' . count($this->mobs));
        $e->xText(10, 50, 'Mode: ' . ($this->fly ? 'Fly (F)' : 'Walk (F)'));
        $e->xText(10, 70, $hasTarget ? 'LMB destroy / RMB place' : 'no target');
        $e->xText(10, 90, 'Esc: menu');

        // visual hotbar: block icons with a selection frame
        $slots = count(self::HOTBAR);
        $cell = 52; $pad = 4; $iw = 44;
        $barW = $slots * $cell;
        $x0 = $cx - (int) ($barW / 2);
        $y0 = $e->xGraphicsHeight() - $cell - 8;
        foreach (self::HOTBAR as $i => $id) {
            $sx = $x0 + $i * $cell;
            $e->xColor(20, 20, 20);
            $e->xRect($sx, $y0, $cell - 2, $cell - 2, 1);             // slot background
            $e->xDrawImage($this->icon[$id], $sx + $pad, $y0 + $pad);  // block icon
            if ($i === $this->slot) {
                $e->xColor(255, 255, 255);
                $e->xRect($sx - 1, $y0 - 1, $cell, $cell, 0);          // selection frame
            }
            $e->xColor(200, 200, 200);
            $e->xText($sx + 4, $y0 + 2, (string) ($i + 1));            // slot number
        }
        // selected block name
        $e->xColor(255, 255, 255);
        $e->xText($cx, $y0 - 18, self::TYPES[$this->selectedType()][0], 1);
    }
