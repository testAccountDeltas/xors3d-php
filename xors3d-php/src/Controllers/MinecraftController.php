    private function terrainTopY(float $wx, float $wz): float
    {
        $bx = $this->cellOf($wx); $bz = $this->cellOf($wz);
        $h = ($bx >= 0 && $bz >= 0 && $bx < $this->wsize && $bz < $this->wsize)
            ? $this->height[$bx][$bz] : self::SEA;
        return $h * self::BLOCK + self::BLOCK / 2;
    }

    private function isWaterAt(float $wx, float $wz): bool
    {
        $bx = $this->cellOf($wx); $bz = $this->cellOf($wz);
        if ($bx < 0 || $bz < 0 || $bx >= $this->wsize || $bz >= $this->wsize) { return false; }
        return $this->height[$bx][$bz] < self::SEA;
    }

    private function spawnMobs(int $count): void
    {
        for ($i = 0; $i < $count; $i++) {
            $tries = 0;
            do {
                $wx = mt_rand(2, $this->wsize - 3) * self::BLOCK;
                $wz = mt_rand(2, $this->wsize - 3) * self::BLOCK;
                $bx = $this->cellOf($wx); $bz = $this->cellOf($wz);
                $gt = $this->groundTop($bx, $bz);
                $onTree = isset($this->cell["$bx," . ($gt + 1) . ",$bz"]); // avoid trees
            } while (($this->isWaterAt($wx, $wz) || $onTree) && ++$tries < 12);
            $this->mobs[] = $this->buildSheep($wx, $wz);
        }
    }

    private function buildSheep(float $wx, float $wz): array
    {
        $e = $this->e; $B = self::BLOCK;
        $pivot = $e->xCreatePivot();
        $parts = [];

        $part = function (float $w, float $h, float $d, int $tex, float $ox, float $oy, float $oz) use ($e, $pivot, &$parts): void {
            $c = $e->xCreateCube();
            $e->xScaleEntity($c, $this->scale * $w, $this->scale * $h, $this->scale * $d);
            $e->xEntityTexture($c, $tex);
            $e->xEntityParent($c, $pivot);
            $e->xPositionEntity($c, $ox, $oy, $oz, 0);
            $parts[] = $c;
        };

        $wool = $this->mobTex['wool']; $leg = $this->mobTex['leg']; $face = $this->mobTex['face'];
        $part(1.1, 0.85, 0.75, $wool, 0,          0.85 * $B, 0);          // body
        $part(0.55, 0.55, 0.55, $wool, 0,         1.05 * $B, 0.62 * $B);  // head
        $part(0.35, 0.35, 0.15, $face, 0,         1.00 * $B, 0.90 * $B);  // muzzle
        foreach ([[-0.35, -0.28], [0.35, -0.28], [-0.35, 0.28], [0.35, 0.28]] as [$lx, $lz]) {
            $part(0.2, 0.55, 0.2, $leg, $lx * $B, 0.28 * $B, $lz * $B);   // legs
        }

        $e->xPositionEntity($pivot, $wx, $this->terrainTopY($wx, $wz), $wz);
        return ['pivot' => $pivot, 'parts' => $parts, 'x' => $wx, 'z' => $wz,
                'dx' => 0.0, 'dz' => 0.0, 'yaw' => 0.0, 'timer' => 0];
    }

    /** Topmost solid block cell in a column (handles built-up / dug terrain). */
    private function groundTop(int $bx, int $bz): int
    {
        if ($bx < 0 || $bz < 0 || $bx >= $this->wsize || $bz >= $this->wsize) {
            return -1;
        }
        $start = ($this->height[$bx][$bz] ?? self::SEA) + 4;
        for ($y = $start; $y >= 0; $y--) {
            if (isset($this->cell["$bx,$y,$bz"])) {
                return $y;
            }
        }
        return $this->height[$bx][$bz] ?? -1;
    }

    /**
     * Can a sheep step into this column from a ground of height $curG?
     * Blocks on: void, cliffs higher than one block, or anything occupying the
     * body space just above the surface (trees, placed blocks).
     */
    private function mobBlocked(int $bx, int $bz, int $curG): bool
    {
        $gt = $this->groundTop($bx, $bz);
        if ($gt < 0) { return true; }                 // void / out of bounds
        if ($gt - $curG > 1) { return true; }         // cliff too tall to climb
        if (isset($this->cell["$bx," . ($gt + 1) . ",$bz"])) { return true; } // obstacle at body
        if (isset($this->cell["$bx," . ($gt + 2) . ",$bz"])) { return true; }
        return false;
    }

    private function mobPickDir(array &$m): void
    {
        if (mt_rand(0, 3) === 0) {
            $m['dx'] = 0.0; $m['dz'] = 0.0;            // idle graze
        } else {
            $a = mt_rand(0, 359) * M_PI / 180.0;
            $m['dx'] = sin($a); $m['dz'] = cos($a);
            $m['yaw'] = $a * 180.0 / M_PI;
        }
    }

    private function mobWalkable(float $nx, float $nz, int $curG): bool
    {
        $B = self::BLOCK;
        $lo = 1.5 * $B; $hi = ($this->wsize - 2.5) * $B;
        if ($nx < $lo || $nx > $hi || $nz < $lo || $nz > $hi) { return false; }
        if ($this->isWaterAt($nx, $nz)) { return false; }
        return !$this->mobBlocked($this->cellOf($nx), $this->cellOf($nz), $curG);
    }

    /** Try to advance, sliding around obstacles by testing nearby headings. */
    private function mobTryStep(array &$m, int $curG, float $spd): bool
    {
        $B = self::BLOCK;
        $base = atan2($m['dx'], $m['dz']);
        foreach ([0, 40, -40, 80, -80, 130, -130, 180] as $deg) {
            $a = $base + $deg * M_PI / 180.0;
            $cdx = sin($a); $cdz = cos($a);
            $nx = $m['x'] + $cdx * $spd * $B;
            $nz = $m['z'] + $cdz * $spd * $B;
            if ($this->mobWalkable($nx, $nz, $curG)) {
                $m['x'] = $nx; $m['z'] = $nz;
                $m['dx'] = $cdx; $m['dz'] = $cdz;
                $m['yaw'] = $a * 180.0 / M_PI;
                return true;
            }
        }
        return false;
    }

    private function updateMobs(): void
    {
        $e = $this->e; $B = self::BLOCK; $spd = 0.05;

        foreach ($this->mobs as &$m) {
            $curG = $this->groundTop($this->cellOf($m['x']), $this->cellOf($m['z']));

            if (--$m['timer'] <= 0) {
                $this->mobPickDir($m);
                $m['timer'] = mt_rand(80, 220);
            }

            if ($m['dx'] !== 0.0 || $m['dz'] !== 0.0) {
                if (!$this->mobTryStep($m, $curG, $spd)) {
                    // boxed in on all sides: pick a new goal shortly
                    $this->mobPickDir($m);
                    $m['timer'] = mt_rand(20, 50);
                }
            }

            $gy = $this->groundTop($this->cellOf($m['x']), $this->cellOf($m['z']));
            $y = (($gy >= 0) ? $gy : self::SEA) * $B + $B / 2;
            $e->xPositionEntity($m['pivot'], $m['x'], $y, $m['z']);
            $e->xRotateEntity($m['pivot'], 0, $m['yaw'], 0);
        }
        unset($m);
    }

    private function clearMobs(): void
    {
        foreach ($this->mobs as $m) {
            foreach ($m['parts'] as $p) { $this->e->xFreeEntity($p); }
            $this->e->xFreeEntity($m['pivot']);
        }
        $this->mobs = [];
    }

