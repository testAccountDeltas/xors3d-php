    private function move(): void
    {
        $e = $this->e;
        $fly = $this->fly;

        // direction from camera transform (so it follows where you look)
        $e->xTFormVector(0, 0, 1, $this->camH, 0);
        $fwx = $e->xTFormedX(); $fwy = $e->xTFormedY(); $fwz = $e->xTFormedZ();
        $e->xTFormVector(1, 0, 0, $this->camH, 0);
        $rgx = $e->xTFormedX(); $rgy = $e->xTFormedY(); $rgz = $e->xTFormedZ();

        if (!$fly) { // project onto XZ for walking
            $fl = hypot($fwx, $fwz) ?: 1.0; $fwx /= $fl; $fwz /= $fl; $fwy = 0.0;
            $rl = hypot($rgx, $rgz) ?: 1.0; $rgx /= $rl; $rgz /= $rl; $rgy = 0.0;
        }

        $spd = $fly ? self::SPD_FLY : self::SPD_WALK;
        $mx = $my = $mz = 0.0;
        if ($e->xKeyDown(Constants::KEY_W)) { $mx += $fwx; $my += $fwy; $mz += $fwz; }
        if ($e->xKeyDown(Constants::KEY_S)) { $mx -= $fwx; $my -= $fwy; $mz -= $fwz; }
        if ($e->xKeyDown(Constants::KEY_D)) { $mx += $rgx; $my += $rgy; $mz += $rgz; }
        if ($e->xKeyDown(Constants::KEY_A)) { $mx -= $rgx; $my -= $rgy; $mz -= $rgz; }
        $ml = hypot(hypot($mx, $my), $mz);
        if ($ml > 0.0) { $mx = $mx / $ml * $spd; $my = $my / $ml * $spd; $mz = $mz / $ml * $spd; }

        $moving = $ml > 0.0;

        $dt = $this->dt;
        if ($fly) {
            $this->px += $mx * $dt; $this->py += $my * $dt; $this->pz += $mz * $dt;
            if ($e->xKeyDown(Constants::KEY_SPACE))  { $this->py += $spd * $dt; }
            if ($e->xKeyDown(Constants::KEY_LSHIFT)) { $this->py -= $spd * $dt; }
        } else {
            $this->moveAxisX($mx * $dt);
            $this->moveAxisZ($mz * $dt);
            $this->applyGravity();
            if ($this->onGround && $e->xKeyHit(Constants::KEY_SPACE)) { $this->vy = self::JUMP; }
            // footsteps
            if ($moving && $this->onGround) {
                $now = $e->xMillisecs();
                if ($now - $this->lastStep > 340) { $this->play($this->sndStep); $this->lastStep = $now; }
            }
            if ($this->py < -30.0) { $this->spawnPlayer(); } // fell out of the world
        }

        $e->xPositionEntity($this->camH, $this->px, $this->py + self::EYE, $this->pz);
    }

    private function blockedAt(float $x, float $z): bool
    {
        $bx = $this->cellOf($x); $bz = $this->cellOf($z);
        $c1 = $this->cellOf($this->py + 0.2);
        $c2 = $this->cellOf($this->py + self::PH - 0.2);
        return $this->solidCell($bx, $c1, $bz) || $this->solidCell($bx, $c2, $bz);
    }

    private function moveAxisX(float $mx): void
    {
        if ($mx === 0.0) { return; }
        $tx = $this->px + $mx + ($mx > 0 ? self::HW : -self::HW);
        if (!$this->blockedAt($tx, $this->pz)) { $this->px += $mx; return; }
        // auto step-up: climb a 1-block rise (hills, stairs) if there is headroom
        if ($this->onGround && $this->canStepUp($tx, $this->pz)) {
            $this->py += self::BLOCK; $this->px += $mx;
        }
    }

    private function moveAxisZ(float $mz): void
    {
        if ($mz === 0.0) { return; }
        $tz = $this->pz + $mz + ($mz > 0 ? self::HW : -self::HW);
        if (!$this->blockedAt($this->px, $tz)) { $this->pz += $mz; return; }
        if ($this->onGround && $this->canStepUp($this->px, $tz)) {
            $this->py += self::BLOCK; $this->pz += $mz;
        }
    }

    /** True if a single block rise here can be climbed (block at feet, clear above). */
    private function canStepUp(float $x, float $z): bool
    {
        $bx = $this->cellOf($x); $bz = $this->cellOf($z);
        $feet = $this->cellOf($this->py + 0.2);
        if (!$this->solidCell($bx, $feet, $bz)) { return false; } // nothing to step onto
        // body must be clear one block higher
        $c1 = $this->cellOf($this->py + self::BLOCK + 0.2);
        $c2 = $this->cellOf($this->py + self::BLOCK + self::PH - 0.2);
        return !$this->solidCell($bx, $c1, $bz) && !$this->solidCell($bx, $c2, $bz);
    }

    private function applyGravity(): void
    {
        $dt = $this->dt;
        $this->vy -= self::G * $dt;
        $ny = $this->py + $this->vy * $dt;
        $bx = $this->cellOf($this->px); $bz = $this->cellOf($this->pz);

        if ($this->vy <= 0.0) {
            $fc = $this->cellOf($ny);
            if ($this->solidCell($bx, $fc, $bz)) {
                $this->py = $fc * self::BLOCK + self::BLOCK / 2 + 0.02;
                $this->vy = 0.0;
                $this->onGround = true;
                return;
            }
            $this->onGround = false;
        } else {
            $hc = $this->cellOf($this->py + self::PH + $this->vy * $dt);
            if ($this->solidCell($bx, $hc, $bz)) { $this->vy = 0.0; return; }
        }
        $this->py = $ny;
    }

    private function animateWater(): void
    {
        if ($this->waterTex === 0 || $this->water === []) { return; }
        $frame = (int) ($this->e->xMillisecs() / 90) % 32;
        foreach (array_keys($this->water) as $w) {
            $this->e->xEntityTexture($w, $this->waterTex, $frame);
        }
    }

    private function gameLoop(int $max): void
    {
        $e = $this->e; $h = $this->camH; $frame = 0;
        $this->lastMs = PHP_INT_MIN;

        while (true) {
            if ($this->closeRequested()) { $this->quit = true; return; }
            if ($max === 0 && $e->xKeyHit(Constants::KEY_ESCAPE)) { return; }

            // Frame time in "60 FPS-frame" units. xMillisecs() is a SIGNED 32-bit ms
            // counter and goes negative after ~24.8 days of uptime, so never test it with
            // "> 0"; use a sentinel for the first frame and treat a negative/huge delta
            // (wrap or hitch) as one frame.
            $now = $e->xMillisecs();
            $frameMs = ($this->lastMs === PHP_INT_MIN) ? 16 : ($now - $this->lastMs);
            $this->lastMs = $now;
            if ($frameMs < 0 || $frameMs > 250) { $frameMs = 16; }
            $frameDt = min(3.0, $frameMs / 16.6667);

            if ($e->xKeyHit(Constants::KEY_F)) { $this->fly = !$this->fly; $this->vy = 0.0; }

            $this->cam->lookOnly();

            // Fixed-timestep physics: run movement/collision/gravity in constant 1/60 s
            // steps regardless of render FPS. This keeps speed AND collision behaviour
            // identical at 60 or 440+ FPS (collision look-ahead no longer scales with the
            // frame's step size). Leftover time carries to the next frame; capped to avoid
            // a spiral of death after a big hitch.
            $this->acc += $frameDt;
            $this->dt = 1.0;
            $steps = 0;
            while ($this->acc >= 1.0 && $steps < 5) {
                $this->move();
                $this->acc -= 1.0;
                $steps++;
            }
            $this->dt = $frameDt; // restore real frame dt for per-frame visuals below

            $this->updateStreaming($this->px, $this->pz);
            $this->processStreaming(2, 2); // budgeted: build a few chunks/frame, no hitches
            $this->animateWater();
            $this->streamMobs();
            $this->updateMobs();

            // block selection: number keys 1-9 (first nine) + mouse wheel (all)
            for ($n = 1; $n <= min(9, count($this->hotbar)); $n++) {
                if ($e->xKeyHit(Constants::KEY_1 + ($n - 1))) { $this->slot = $n - 1; $this->refreshHand($e); }
            }
            $wheel = $e->xMouseZSpeed();
            if ($wheel !== 0) {
                $c = count($this->hotbar);
                $this->slot = (($this->slot - ($wheel > 0 ? 1 : -1)) % $c + $c) % $c;
                $this->refreshHand($e);
            }
            $e->xTurnEntity($this->hand, 0, 1.5 * $this->dt, 0);
            $this->updateSky();
            $this->updateSkyObjects();
            $this->updateWeather();
            $this->updatePuddles();
            $this->updateParticles();
            $this->updatePointLights();

            $cx = (int) ($e->xGraphicsWidth() / 2);
            $cy = (int) ($e->xGraphicsHeight() / 2);
            $e->xCameraPick($h, $cx, $cy);
            $picked = $e->xPickedEntity();
            $hasTarget = $picked !== 0 && isset($this->meshCk[$picked]);

            if ($hasTarget) {
                // pick point + face normal -> the block cell just inside / outside the face
                $px = $e->xPickedX(); $py = $e->xPickedY(); $pz = $e->xPickedZ();
                [$dx, $dy, $dz] = $this->faceOffset($e);
                $q = self::BLOCK * 0.25;
                if ($e->xMouseHit(1)) {
                    $bx = $this->cellOf($px - $dx * $q);
                    $by = $this->cellOf($py - $dy * $q);
                    $bz = $this->cellOf($pz - $dz * $q);
                    $this->destroyAt($e, $bx, $by, $bz);
                } elseif ($e->xMouseHit(2) || $e->xMouseHit(3)) {
                    $bx = $this->cellOf($px + $dx * $q);
                    $by = $this->cellOf($py + $dy * $q);
                    $bz = $this->cellOf($pz + $dz * $q);
                    $this->placeAt($e, $bx, $by, $bz, $this->selectedType());
                } elseif ($e->xKeyHit(Constants::KEY_E)) {
                    // E opens/closes the targeted door
                    $bx = $this->cellOf($px - $dx * $q);
                    $by = $this->cellOf($py - $dy * $q);
                    $bz = $this->cellOf($pz - $dz * $q);
                    $this->toggleDoor($bx, $by, $bz);
                }
            }

            // C opens the crafting / block menu (assigns a block to the active slot)
            if ($e->xKeyHit(Constants::KEY_C)) { $this->craftMenu(); }

            if ($max > 0 && getenv('CRAFT_LOOKUP')) { $e->xRotateEntity($h, -40, 40, 0); }

            $e->xRenderWorld();
            $this->renderGodRays();
            $this->renderBloom();
            $this->drawHud($e, $hasTarget);

            if ($max > 0 && $frame + 1 >= $max && ($shot = getenv('CRAFT_SHOT'))) {
                $e->xSaveBuffer($e->xBackBuffer(), $shot);
            }
            $e->xFlip();
            if ($max > 0 && ++$frame >= $max) { return; }
        }
    }

    private function drawHud(Engine $e, bool $hasTarget): void
    {
        $w = $e->xGraphicsWidth();
        $cx = (int) ($w / 2);
        $cy = (int) ($e->xGraphicsHeight() / 2);

        // crosshair (two lines)
        $e->xColor(255, 255, 255);
        $e->xLine($cx - 9, $cy, $cx + 9, $cy);
        $e->xLine($cx, $cy - 9, $cx, $cy + 9);

        $e->xColor(255, 255, 0);
        $e->xText(10, 10, 'FPS: ' . $e->xGetFPS());
        $e->xColor(220, 220, 220);
        $e->xText(10, 30, 'Chunks: ' . count($this->chunkMesh) . '   Mobs: ' . count($this->mobs));
        $e->xText(10, 50, 'Mode: ' . ($this->fly ? 'Fly (F)' : 'Walk (F)'));
        $e->xText(10, 70, $hasTarget ? 'LMB destroy / RMB place / E door' : 'no target');
        $e->xText(10, 90, 'C: craft menu    Esc: menu');

        // visual hotbar: block icons with a selection frame
        $slots = count($this->hotbar);
        $cell = 52; $pad = 4; $iw = 44;
        $barW = $slots * $cell;
        $x0 = $cx - (int) ($barW / 2);
        $y0 = $e->xGraphicsHeight() - $cell - 8;
        foreach ($this->hotbar as $i => $id) {
            $sx = $x0 + $i * $cell;
            $cnt = $this->invCount($id);
            $e->xColor(20, 20, 20);
            $e->xRect($sx, $y0, $cell - 2, $cell - 2, 1);             // slot background
            $e->xDrawImage($this->icon[$id], $sx + $pad, $y0 + $pad);  // block icon
            if ($i === $this->slot) {
                $e->xColor(255, 255, 255);
                $e->xRect($sx - 1, $y0 - 1, $cell, $cell, 0);          // selection frame
            }
            $e->xColor(200, 200, 200);
            $e->xText($sx + 4, $y0 + 2, (string) ($i + 1));            // slot number
            // held count (bottom-right), red when empty
            if ($cnt > 0) { $e->xColor(255, 255, 255); } else { $e->xColor(210, 90, 90); }
            $e->xText($sx + $cell - 22, $y0 + $cell - 18, (string) $cnt);
        }
        // selected block name
        $e->xColor(255, 255, 255);
        $e->xText($cx, $y0 - 18, self::TYPES[$this->selectedType()][0], 1);
    }

