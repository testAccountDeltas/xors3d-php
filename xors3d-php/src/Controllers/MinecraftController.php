    private function spawnPlayer(): void
    {
        $this->px = $this->originX;
        $this->pz = $this->originZ;
        $this->py = (self::MAX_H + 6) * self::BLOCK;
        $this->vy = 0.0;
        $this->onGround = false;
        $this->cam->reset();
        $this->e->xPositionEntity($this->camH, $this->px, $this->py + self::EYE, $this->pz);
        $this->streamCX = PHP_INT_MAX;              // force streaming refresh
        $this->updateStreaming($this->px, $this->pz); // queue the world around spawn
        $this->processStreaming(12, 0);            // build just the near ring now (ground under
                                                   // the player); the rest streams in per-frame
        $this->clearMobs();                        // sheep re-stream around the new spot
        $this->mobTimer = 0;
        $seed = min(4, (int) $this->settings['mobs']);
        for ($i = 0; $i < $seed; $i++) { $this->spawnMobNear(); } // a few right away
    }

    // ================================================================ settings

    private function settingsFile(): string { return dirname(__DIR__, 2) . '/craft-settings.json'; }

    private function loadSettings(): void
    {
        $f = $this->settingsFile();
        if (is_file($f) && ($json = json_decode((string) file_get_contents($f), true)) !== null) {
            foreach ($this->settings as $k => $v) {
                if (isset($json[$k])) {
                    $this->settings[$k] = is_float($v) ? (float) $json[$k] : (is_int($v) ? (int) $json[$k] : $json[$k]);
                }
            }
        }
    }

    private function saveSettings(): void
    {
        @file_put_contents($this->settingsFile(), json_encode($this->settings, JSON_PRETTY_PRINT));
    }

    private function applySettings(): void
    {
        $this->cam->setSensitivity((float) $this->settings['sensitivity']);
        $this->cam->setInvertY((bool) $this->settings['invertY']);
        $this->e->xCameraZoom($this->camH, (float) $this->settings['fov']);
        $this->e->xCameraFogMode($this->camH, (int) $this->settings['fog'] ? 1 : 0);
        if ($this->ambCh !== 0) {
            $this->e->xChannelVolume($this->ambCh, (float) $this->settings['volume'] * 0.6);
        }
        $this->applyRenderDist();
    }


    // =================================================================== sound

    private function loadSounds(Engine $e): void
    {
        $dir = dirname(__DIR__, 2) . '/assets/sounds/';
        if (is_file($dir . 'break.wav'))   { $this->sndBreak   = $e->xLoadSound($dir . 'break.wav'); }
        if (is_file($dir . 'place.wav'))   { $this->sndPlace   = $e->xLoadSound($dir . 'place.wav'); }
        if (is_file($dir . 'step.wav'))    { $this->sndStep    = $e->xLoadSound($dir . 'step.wav'); }
        if (is_file($dir . 'ambient.wav')) {
            $this->sndAmbient = $e->xLoadSound($dir . 'ambient.wav');
            if ($this->sndAmbient !== 0) {
                $e->xLoopSound($this->sndAmbient);
                $this->ambCh = $e->xPlaySound($this->sndAmbient);
            }
        }
    }

    private function play(int $sound): void
    {
        $vol = (float) $this->settings['volume'];
        if ($sound === 0 || $vol <= 0.0) {
            return;
        }
        $this->e->xSoundVolume($sound, $vol);
        $this->e->xPlaySound($sound);
    }

