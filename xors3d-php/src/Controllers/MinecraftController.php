    private function exposedBottom(int $x, int $z): int
    {
        $min = $this->heightAt($x, $z);
        foreach ([[1, 0], [-1, 0], [0, 1], [0, -1]] as [$dx, $dz]) {
            $nx = $x + $dx; $nz = $z + $dz;
            $nh = $this->heightAt($nx, $nz);
            $min = min($min, $nh);
        }
        return max(0, $min);
    }

