    private function buildTemplates(Engine $e): void
    {
        $base = dirname(__DIR__, 2) . '/assets/blocks/';
        foreach (self::TYPES as $id => [$name, $file]) {
            $cube = $e->xCreateCube();
            if ($id === 1) {
                $w = $e->xMeshWidth($cube);
                $this->scale = $w > 0.0 ? self::BLOCK / $w : 1.0;
            }
            $e->xScaleEntity($cube, $this->scale, $this->scale, $this->scale);
            $texture = $e->xLoadTexture($base . $file);
            $this->tex[$id] = $texture;
            $e->xEntityTexture($cube, $texture);
            if ($id === 11) { $e->xEntityFX($cube, 1); } // glowstone: fullbright
            if ($id === 10) { $e->xEntityAlpha($cube, 0.7); } // glass: translucent
            $e->xHideEntity($cube);
            $this->template[$id] = $cube;
        }

        // animated translucent water
        $this->waterTex = $e->xLoadAnimTexture($base . 'water.png', 1, 16, 16, 0, 32);
        $this->waterTpl = $e->xCreateCube();
        $e->xScaleEntity($this->waterTpl, $this->scale, $this->scale, $this->scale);
        $e->xEntityColor($this->waterTpl, 120, 160, 255);
        $e->xEntityAlpha($this->waterTpl, 0.7);
        $e->xEntityTexture($this->waterTpl, $this->waterTex);
        $e->xHideEntity($this->waterTpl);
    }

    private function createHand(Engine $e, int $camera): void
    {
        $this->hand = $e->xCreateCube();
        $s = $this->scale * 0.22;
        $e->xScaleEntity($this->hand, $s, $s, $s);
        $e->xEntityParent($this->hand, $camera);
        $e->xEntityFX($this->hand, 1);
        $e->xPositionEntity($this->hand, 0.95, -0.75, 2.6, 0);
        $e->xRotateEntity($this->hand, 15, 35, 0, 0);
        $this->refreshHand($e);
    }

    private function refreshHand(Engine $e): void
    {
        if ($this->hand !== 0) {
            $e->xEntityTexture($this->hand, $this->tex[$this->selectedType()]);
        }
    }

    // ============================================================ world (gen)

    private function clearWorld(): void
    {
        $e = $this->e;
        $this->clearMobs();
        foreach ($this->cell as $h) { $e->xFreeEntity($h); }
        foreach ($this->waterList as $h) { $e->xFreeEntity($h); }
        $this->cell = $this->cellType = $this->entToCell = $this->waterList = $this->height = [];
        $this->chunk = $this->entChunk = $this->chunkVis = [];
        $this->lastPC = '';
    }

    private function rebuildWorld(): void
    {
        $this->clearWorld();
        $this->wsize = (int) $this->settings['worldSize'];
        $this->generateWorld($this->e);
    }

    private function generateWorld(Engine $e): void
    {
        $n = $this->wsize;
        $this->seed = mt_rand() / mt_getrandmax() * 1000.0;

        // multi-octave value noise -> rolling hills, mountains and a few lakes.
        // Land should dominate: map noise across [SEA-1 .. MAX_H] so most of the
        // world is above the water line, with occasional low basins as lakes.
        for ($x = 0; $x < $n; $x++) {
            for ($z = 0; $z < $n; $z++) {
                $f = $this->fbm($x * 0.08, $z * 0.08) / 0.9375;   // 0..1, avg ~0.5
                $h = (int) round((self::SEA - 1) + $f * (self::MAX_H - (self::SEA - 1)));
                $this->height[$x][$z] = max(0, min(self::MAX_H, $h));
            }
        }

        for ($x = 0; $x < $n; $x++) {
            for ($z = 0; $z < $n; $z++) {
                $top = $this->height[$x][$z];
                for ($y = $this->exposedBottom($x, $z); $y <= $top; $y++) {
                    $this->spawn($e, $x, $y, $z, $this->groundType($x, $y, $z));
                }
            }
        }

        $trees = (int) ($n * $n * 0.03 * (float) $this->settings['trees']);
        for ($i = 0; $i < $trees; $i++) {
            $x = mt_rand(2, $n - 3); $z = mt_rand(2, $n - 3);
            $h = $this->height[$x][$z];
            if ($h < self::SNOW && $h > self::SEA) {
                $this->plantTree($e, $x, $h + 1, $z);
            }
        }

        if ((int) $this->settings['water']) {
            for ($x = 0; $x < $n; $x++) {
                for ($z = 0; $z < $n; $z++) {
                    if ($this->height[$x][$z] < self::SEA) {
                        $this->spawnWater($e, $x, self::SEA, $z);
                    }
                }
            }
        }

        $this->spawnMobs((int) $this->settings['mobs']);
    }

    // ------------------------------------------------------------- value noise

    private function hash2(float $x, float $z): float
    {
        $h = sin($x * 127.1 + $z * 311.7 + $this->seed) * 43758.5453;
        return $h - floor($h);
    }

    private function vnoise(float $x, float $z): float
    {
        $x0 = floor($x); $z0 = floor($z);
        $fx = $x - $x0;  $fz = $z - $z0;
        $u = $fx * $fx * (3 - 2 * $fx);
        $v = $fz * $fz * (3 - 2 * $fz);
        $a = $this->hash2($x0, $z0);       $b = $this->hash2($x0 + 1, $z0);
        $c = $this->hash2($x0, $z0 + 1);   $d = $this->hash2($x0 + 1, $z0 + 1);
        return ($a * (1 - $u) + $b * $u) * (1 - $v) + ($c * (1 - $u) + $d * $u) * $v;
    }

    private function fbm(float $x, float $z): float
    {
        $sum = 0.0; $amp = 0.5; $freq = 1.0;
        for ($o = 0; $o < 4; $o++) {
            $sum += $amp * $this->vnoise($x * $freq, $z * $freq);
            $amp *= 0.5; $freq *= 2.0;
        }
        return $sum; // 0 .. 0.9375
    }

