    public function index(int|string $maxFrames = 0): int
    {
        $max = (int) $maxFrames;
        $e = $this->e = $this->engine;

        $this->loadSettings();

        $e->xKey($this->config->firstKey());
        $e->xSetAntiAliasType($e->xGetMaxAntiAlias());
        $e->xAppTitle('Craft - Xors3d voxel game (PHP)');
        $e->xGraphics3D((int) $this->settings['width'], (int) $this->settings['height'], 32, 0, (int) $this->settings['vsync']);
        $e->xAntiAlias(1);
        $e->xSetTextureFiltering(Constants::TF_POINT);
        $e->xHidePointer();

        $this->cam = new MouseLookCamera($e);
        $this->camH = $this->cam->handle();
        $e->xCameraClsColor($this->camH, 115, 185, 245);
        $e->xCameraRange($this->camH, 0.2, 600);
        $e->xCameraFogColor($this->camH, 115, 185, 245);
        $e->xCameraFogRange($this->camH, 60, 260);

        $this->sun = $e->xCreateLight(Constants::LIGHT_DIRECTIONAL);
        $e->xRotateEntity($this->sun, 50, 30, 0);
        $this->moon = $e->xCreateLight(Constants::LIGHT_DIRECTIONAL);
        $e->xRotateEntity($this->moon, 230, 30, 0);
        $e->xLightColor($this->moon, 0, 0, 0);
        $e->xAmbientLight(120, 120, 130);

        // pool of point lights reassigned each frame to the nearest torches/glowstone
        // (real additive glow around the player's lights, works in dark caves at night)
        for ($i = 0; $i < 5; $i++) {
            $l = $e->xCreateLight(Constants::LIGHT_POINT);
            $e->xLightColor($l, 255, 205, 130);          // warm torchlight
            $e->xLightRange($l, 11.0 * self::BLOCK);
            $e->xHideEntity($l);
            $this->pointLights[] = $l;
        }
        $e->xLoadFont('Arial', 14);

        $this->buildTemplates($e);
        $this->loadIcons($e);
        $this->loadMobTextures($e);
        $this->createSky($e);
        $this->createHand($e, $this->camH);
        $this->pivot = $e->xCreatePivot();
        $this->loadSounds($e);
        $this->setupBloom($e);
        $this->setupGodRays($e);
        $this->applySettings();
        $this->rebuildWorld();

        if ($max > 0) {
            $this->spawnPlayer();
            $this->gameLoop($max);
            $e->xReleaseGraphics();
            return 0;
        }

        if (getenv('CRAFT_SETSHOT')) { $this->settingsMenu(); $e->xReleaseGraphics(); return 0; }

        while (!$this->quit) {
            $action = $this->mainMenu();
            if ($this->quit || $action === 'quit') {
                break;
            }
            if ($action === 'save')     { $this->saveWorld(); continue; }
            if ($action === 'load')     { $this->loadWorld(); continue; }
            if ($action === 'settings') { $this->settingsMenu(); continue; }
            if ($action === 'new')      { $this->rebuildWorld(); $this->status = 'New world generated.'; }
            $this->spawnPlayer();
            $this->gameLoop(0);
        }

        $e->xReleaseGraphics();
        return 0;
    }

